"""
Builds the two lists cookieZ ships, from a downloaded copy of the Open
Cookie Database (Apache-2.0, https://github.com/jkwakman/Open-Cookie-Database).

    python make_lists.py <open-cookie-database.json> <its LICENSE> <commit>

This script never downloads anything, and neither does the extension: the
lists are files inside it, so they only change when cookieZ is updated.
Download the two files from the commit you want, then run this.

Writes, in src/lists/:
  trackers.js       the domains behind known advertising and analytics
                    cookies, which "Block known trackers' cookies" blocks
  known-cookies.js  cookie names, who sets them and what for, which the
                    table and editor use to name a cookie
  LICENSE-OpenCookieDatabase.txt  the licence, and what was changed

They're JavaScript modules rather than JSON because the extension never
calls fetch(), not even for its own files (see test_no_network.py).
"""

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "src" / "lists"

# Companies whose own sites people sign in to. Blocking their domain would
# block their cookies on their own site too, so signing in to them would
# break. 1.7's "block other companies' cookies on every site" still catches
# them on other sites.
SIGN_IN_SITES = {
    "google.com", "youtube.com", "facebook.com", "instagram.com", "whatsapp.com",
    "microsoft.com", "bing.com", "live.com", "office.com", "linkedin.com",
    "twitter.com", "x.com", "tiktok.com", "pinterest.com", "reddit.com",
    "amazon.com", "yahoo.com", "apple.com", "snapchat.com", "yandex.ru",
    "yandex.com", "baidu.com", "vk.com", "hubspot.com", "salesforce.com",
    "adobe.com", "shopify.com", "wordpress.com", "github.com", "paypal.com",
    "stripe.com", "zendesk.com", "intercom.io", "spotify.com", "vimeo.com",
    "bit.ly",
}

# Not trackers in the sense people mean, or needed for sites to work: sites
# people use directly, sign-in and consent services, comments, chat, forms,
# reviews and audio players embedded on other sites, and Google's and
# Twitter's static and link domains.
NEEDED = {
    "wikimedia.org", "indeed.com", "mercadolibre.com", "funda.nl", "issuu.com",
    "trustpilot.com", "typeform.com", "wix.com", "disqus.com", "tawk.to",
    "onetrust.com", "gigya.com", "gstatic.com", "t.co", "streamtheworld.com",
    "byteoversea.com",
}

# Two-part endings, so "ads.example.co.uk" becomes "example.co.uk".
TWO_PART_ENDINGS = {
    "co.uk", "org.uk", "com.au", "net.au", "com.tr", "co.jp", "com.br",
    "co.nz", "co.za", "com.cn", "com.mx", "co.in", "co.kr", "com.sg",
}


def main_domain(host):
    parts = host.split(".")
    if len(parts) >= 3 and ".".join(parts[-2:]) in TWO_PART_ENDINGS:
        return ".".join(parts[-3:])
    return ".".join(parts[-2:])


def clean_domain(raw):
    """The cookie's domain as a plain host, or None if it isn't one."""
    d = raw.lower().replace("​", "")
    d = d.split(" or ")[0].replace("(3rd party)", "").strip().strip(".")
    if not re.fullmatch(r"[a-z0-9-]+(\.[a-z0-9-]+)+", d):
        return None
    return d


def first_sentence(text, limit=160):
    text = " ".join(text.split())
    end = re.search(r"(?<=[a-z0-9)])\. ", text)
    if end:
        text = text[:end.start() + 1]
    if len(text) > limit:
        text = text[:limit - 1].rsplit(" ", 1)[0] + "…"
    return text


def module(name, comment, value):
    # One entry per line, so a diff shows what changed between versions.
    lines = [json.dumps(v, ensure_ascii=False, separators=(",", ":")) for v in value]
    body = "[\n  " + ",\n  ".join(lines) + "\n]"
    return f"// {comment}\n// Generated by tests/make_lists.py. Do not edit by hand.\n\nexport const {name} = {body};\n"


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    licence = Path(sys.argv[2]).read_text(encoding="utf-8")
    commit = sys.argv[3]
    source = f"Open Cookie Database, commit {commit[:12]}"

    trackers = set()
    known = []
    for platform, entries in data.items():
        for e in entries:
            name = e["cookie"].strip()
            if name:
                known.append({
                    "name": name,
                    "prefix": e["wildcardMatch"] == "1",
                    "by": platform.strip(),
                    "kind": e["category"],
                    "what": first_sentence(e["description"]),
                })
            if e["category"] in ("Marketing", "Analytics"):
                d = clean_domain(e["domain"])
                if d and main_domain(d) not in SIGN_IN_SITES | NEEDED:
                    trackers.add(main_domain(d))

    known.sort(key=lambda k: (k["name"].lower(), k["by"]))
    tracker_list = sorted(trackers)

    OUT.mkdir(exist_ok=True)
    (OUT / "trackers.js").write_text(module(
        "TRACKER_DOMAINS",
        f"Domains behind known advertising and analytics cookies, from the {source}.",
        tracker_list), encoding="utf-8", newline="\n")
    (OUT / "known-cookies.js").write_text(module(
        "KNOWN_COOKIES",
        f"Known cookie names, from the {source}. Descriptions shortened to one sentence.",
        known), encoding="utf-8", newline="\n")
    (OUT / "LICENSE-OpenCookieDatabase.txt").write_text(
        "trackers.js and known-cookies.js in this folder are made from the\n"
        "Open Cookie Database, https://github.com/jkwakman/Open-Cookie-Database,\n"
        f"commit {commit}, under the Apache License 2.0 below.\n\n"
        "Changes made by cookieZ: only the cookie name, its company, category and\n"
        "the first sentence of its description are kept; the advertising and\n"
        "analytics cookies' domains are reduced to their main domain, and\n"
        "companies whose own sites people sign in to are left out.\n\n"
        + licence, encoding="utf-8", newline="\n")

    print(f"{len(tracker_list)} tracker domains, {len(known)} known cookie names")
    for f in ("trackers.js", "known-cookies.js"):
        print(f"  {f}: {(OUT / f).stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
